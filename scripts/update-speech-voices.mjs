// synthesis, execution of vendor JavaScript, or application startup networking.
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';

export const CATALOGUE_ENDPOINT='https://aistudio.cloud.tencent.com/demo-common/democase/getCommonResult';
export const CATALOGUE_DOCUMENT='https://cloud.tencent.com/document/product/1073/92668';
export const CATALOGUE_REQUEST=Object.freeze({action:'DescribeVoices',from:'tts-demo',module:'tts',payload:Object.freeze({WebsiteType:0})});
export const SAMPLE_ORIGIN='https://tts-tone-audio-1300466766.cos.ap-shanghai.myqcloud.com';
const DISCOVERY_SOURCE='https://ttsdemo-static-file-1300466766.cos.ap-guangzhou.myqcloud.com/20251121/app.3813a612.js';
const CATEGORY={2:'premium',3:'large-model',4:'supernatural'};
const RATE={'premium':.3,'large-model':1.2,'supernatural':6.5};
const plain=v=>v!==null&&typeof v==='object'&&!Array.isArray(v);
const text=(v,max=120)=>typeof v==='string'&&v.length<=max&&!/[\x00-\x1f\x7f<>]/.test(v);
const reject=()=>{throw new Error('Tencent public catalogue failed validation; existing catalogue was not changed');};
const clean=v=>v.replace(/<[^>]*>/g,'').replace(/&nbsp;|&#160;/g,' ').replace(/&amp;/g,'&').trim();

export function parseBasicSpeechTable(html){
  if(typeof html!=='string'||html.length>4*1024*1024)reject();
  const heading=[...html.matchAll(/<h2\b[^>]*>[\s\S]*?<\/h2>/g)].find(m=>clean(m[0])==='基础语音合成音色列表');
  if(!heading)reject();
  const table=html.slice(heading.index+heading[0].length).match(/<table\b[^>]*>[\s\S]*?<\/table>/)?.[0];
  if(!table)reject();
  const rows=[...table.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g)].map(m=>[...m[1].matchAll(/<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/g)].map(m=>clean(m[1]))).slice(1);
  const result=new Map();
  for(const row of rows){
    const [id,name,style,kind,language,rates]=row,voiceType=Number(id);
    if(row.length!==7||!/^\d+$/.test(id)||!Number.isSafeInteger(voiceType)||voiceType<=0||result.has(voiceType)||!text(name)||!text(style)||!text(language)||!rates.includes('16k'))reject();
    const category=kind==='精品音色'?'premium':kind==='大模型音色'?'large-model':kind==='超自然大模型音色'?'supernatural':null;
    const normalizedLanguage=language==='中英文'?'zh-CN,en-US':language==='中文'?'zh-CN':language==='英文'?'en-US':null;
    if(!category||!normalizedLanguage)reject();
    result.set(voiceType,{name,style,category,language:normalizedLanguage});
  }
  if(result.size<6||result.size>1000)reject();
  return result;
}

export function buildSpeechVoiceCatalogue(response,html){
  const basic=parseBasicSpeechTable(html),groups=response?.data?.Response?.CategoryVoiceList;
  if(response?.code!==0||!Array.isArray(groups)||groups.length<1||groups.length>50)reject();
  const voices=[],seen=new Set();
  for(const group of groups){
    if(!plain(group)||!text(group.CategoryName,40)||!group.CategoryName||!Array.isArray(group.VoiceList))reject();
    for(const voice of group.VoiceList){
      if(!plain(voice)||!Number.isSafeInteger(voice.VoiceType)||voice.VoiceType<=0||seen.has(voice.VoiceType)||!text(voice.VoiceName)||!voice.VoiceName||!text(voice.VoiceDesc)||!['male','female','boy','girl'].includes(voice.VoiceGender))reject();
      const doc=basic.get(voice.VoiceType),category=CATEGORY[voice.VoiceQuality];
      if(!doc||doc.name!==voice.VoiceName||category!==doc.category)reject();
      // Keep only exact URLs supplied by Tencent. Its bucket currently rejects
      // off-site requests by referer rule, so do not advertise these as playable
      // samples or work around that rule by forging request headers.
      if(typeof voice.VoiceAudio!=='string'||voice.VoiceAudio.length>1000)reject();
      const sample=new URL(voice.VoiceAudio);
      if(sample.origin!==SAMPLE_ORIGIN||sample.username||sample.password||sample.search||sample.hash||!/\.(?:wav|mp3)$/i.test(sample.pathname))reject();
      seen.add(voice.VoiceType);
      voices.push({voiceType:voice.VoiceType,name:voice.VoiceName,gender:['male','boy'].includes(voice.VoiceGender)?'male':'female',style:voice.VoiceDesc||doc.style,language:doc.language,category,scenario:group.CategoryName,sampleRate:16000,rateCnyPer10k:RATE[category],sampleUrl:null,sampleAvailability:'official-site-only',source:CATALOGUE_DOCUMENT});
    }
  }
  if(seen.size!==basic.size||[101001,101055,101026,101004,101030,101013].some(id=>!seen.has(id)))reject();
  return voices.sort((a,b)=>a.voiceType-b.voiceType);
}

export function renderSpeechVoiceModule(voices,metadata){
  return '// Generated by scripts/update-speech-voices.mjs; facts from Tencent public catalogue.\n'
    +'// Offline at runtime. IDs are cross-checked against the basic TextToVoice table.\n'
    +'// Official samples currently enforce an official-site referer rule; no header spoofing.\n'
    +'export const TENCENT_SPEECH_SAMPLE_ORIGINS=Object.freeze([]);\n'
    +'export const TENCENT_SPEECH_VOICE_CATALOGUE=Object.freeze('+JSON.stringify(metadata,null,2)+');\n'
    +'export const TENCENT_SPEECH_VOICES=Object.freeze('+JSON.stringify(voices,null,2)+'.map(voice=>Object.freeze(voice)));\n';
}

async function boundedFetch(url,options={},maxBytes=4*1024*1024,expectedType='text/html'){
  const response=await fetch(url,{...options,credentials:'omit',redirect:'error',signal:AbortSignal.timeout(20000)});
  if(!response.ok||Number(response.headers.get('content-length'))>maxBytes||response.headers.get('content-type')?.toLowerCase().split(';')[0].trim()!==expectedType)reject();
  const reader=response.body?.getReader();if(!reader)reject();
  const chunks=[];let size=0;
  try{for(;;){const row=await reader.read();if(row.done)break;size+=row.value.length;if(size>maxBytes)reject();chunks.push(row.value);}}
  finally{await reader.cancel().catch(()=>{});}
  return Buffer.concat(chunks).toString('utf8');
}

async function main(){
  const args=process.argv.slice(2);if(args.some(a=>a!=='--write')||args.length>1)throw new Error('Usage: node scripts/update-speech-voices.mjs [--write]');
  const [raw,document,discovery]=await Promise.all([
    boundedFetch(CATALOGUE_ENDPOINT,{method:'POST',headers:{'content-type':'application/json;charset=UTF-8'},body:JSON.stringify(CATALOGUE_REQUEST)},2*1024*1024,'application/json'),
    boundedFetch(CATALOGUE_DOCUMENT),
    boundedFetch(DISCOVERY_SOURCE,{},2*1024*1024,'application/x-javascript')
  ]);
  const voices=buildSpeechVoiceCatalogue(JSON.parse(raw),document);
  const target=new URL('../src/speech-voices.js',import.meta.url);
  const previous=await import(pathToFileURL(fileURLToPath(target)).href).catch(()=>({TENCENT_SPEECH_VOICES:[]}));
  const old=new Map(previous.TENCENT_SPEECH_VOICES.map(v=>[v.voiceType,v])),next=new Map(voices.map(v=>[v.voiceType,v]));
  console.log(JSON.stringify({count:voices.length,added:voices.filter(v=>!old.has(v.voiceType)).map(v=>v.voiceType),removed:[...old.keys()].filter(id=>!next.has(id)),changed:voices.filter(v=>old.has(v.voiceType)&&JSON.stringify(old.get(v.voiceType))!==JSON.stringify(v)).map(v=>v.voiceType),write:args.includes('--write')},null,2));
  if(!args.includes('--write'))return;
  const metadata={verifiedAt:new Date().toISOString().slice(0,10),endpoint:CATALOGUE_ENDPOINT,request:CATALOGUE_REQUEST,document:CATALOGUE_DOCUMENT,pricingDocument:'https://cloud.tencent.com/document/product/1073/34112',discoverySource:DISCOVERY_SOURCE,discoverySha256:crypto.createHash('sha256').update(discovery).digest('hex'),scope:'public-DescribeVoices-cross-checked-basic-TextToVoice',count:voices.length,pricingBasis:'general-synthesis-lowest-daily-volume-list-price-excludes-resource-pack',sampleAvailability:'official-site-only',sampleVerification:'2026-10-23 public GET denied by official bucket referer rule',documentSha256:crypto.createHash('sha256').update(document).digest('hex')};
  const temp=new URL('../src/speech-voices.js.next',import.meta.url);
  await fs.writeFile(temp,renderSpeechVoiceModule(voices,metadata),'utf8');await fs.rename(temp,target);
}
if(process.argv[1]&&pathToFileURL(process.argv[1]).href===import.meta.url)main().catch(error=>{console.error(error.message);process.exitCode=1;});
